ALTER TABLE public.finances_request ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.finances_record ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.finances_loan ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.finances_goal ENABLE ROW LEVEL SECURITY;
